"""Turn the pair records into the tables of record.

    python examples/admission-slack/pairs.py --all --out runs/
    python examples/admission-slack/pairs.py --suite banking --config banking_tuned.yaml --out runs/
    python examples/admission-slack/report.py runs/ > examples/admission-slack/results.md

Everything this prints is derived from the JSON records, so a number in
``results.md`` can always be traced back to a pair: no figure is typed in by hand.
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import os
from typing import Any

BUCKETS = ("orig_allowed_sub_allowed", "orig_allowed_sub_denied", "orig_denied")


def load(run_dir: str) -> list[dict[str, Any]]:
    out = []
    for path in sorted(glob.glob(os.path.join(run_dir, "*.json"))):
        with open(path) as fh:
            d = json.load(fh)
        if not isinstance(d, dict) or "summary" not in d:
            continue  # enrichment / neighbour records live in the same directory
        d["_file"] = os.path.basename(path)
        out.append(d)
    return out


def _fmt(v: Any, width: int = 34) -> str:
    s = str(v)
    s = s.replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= width else s[: width - 1] + "…"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir")
    ap.add_argument("--enrichment", help="the JSON written by enrichment.py")
    ap.add_argument("--neighbor", help="directory of verdicts-*.json written by neighbor_opa.py")
    args = ap.parse_args()
    runs = load(args.run_dir)

    print("# Admission slack on AgentDojo — measured record\n")
    print("Generated by `examples/admission-slack/report.py` from the JSON pair")
    print("records; do not edit by hand. Each run is one suite under one deployment")
    print("configuration, replayed over the suite's own reference plans")
    print("(AgentDojo `ground_truth`) with a real `ToolCallGovernor`. No model is in")
    print("the loop, so these are facts about the monitor's admission behaviour on")
    print("the reference plans — not about what an agent would emit, and not an")
    print("upper bound on utility over all ways of solving a task.\n")

    print("## 1. Coverage and verdicts on the reference plans\n")
    print("| run | tasks | effectful calls | calls allowed | pairs probed | π violations |")
    print("|---|---|---|---|---|---|")
    for d in runs:
        s = d["summary"]
        print(f"| {s['suite']} · {s['config']} · integrity={s['integrity']} | {s['tasks_total']} "
              f"| {s['effectful_calls']} | {s['calls_allowed']} | {s['pairs']} | {s['pi_violations']} |")
    tot_pairs = sum(d["summary"]["pairs"] for d in runs)
    tot_viol = sum(d["summary"]["pi_violations"] for d in runs)
    print(f"\n**Theorem-2 obligation check:** {tot_pairs} pairs, {tot_viol} projection")
    print("violations. A violation would be a pair with *equal* projections and")
    print("unequal verdicts — i.e. a verdict reading something the observation")
    print("language in `observation.py` does not list. None was found, so the")
    print("projection is faithful for this deployment of this kernel.\n")

    print("## 2. The three buckets\n")
    print("Counted separately — alternative values, full calls and tasks are three")
    print("different quantities and are never added together.\n")
    print("| run | orig allowed · sub allowed | orig allowed · sub denied | orig denied "
          "| forced & executable | forced calls | forced tasks | referential | ref. calls | ref. tasks |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for d in runs:
        s, b = d["summary"], d["summary"]["buckets"]
        print(f"| {s['suite']} · {s['config']} | {b.get('orig_allowed_sub_allowed', 0)} "
              f"| {b.get('orig_allowed_sub_denied', 0)} | {b.get('orig_denied', 0)} "
              f"| {s['forced_executable_substitutions']} | {s['forced_calls']} | {s['forced_tasks']} "
              f"| {s['referential_forced_substitutions']} | {s['referential_calls']} "
              f"| {s['referential_tasks']} |")
    print("\n*forced & executable* = the substitution has the **same projection** as the")
    print("original (so Theorem 2 forces the same verdict), was **admitted**, and the")
    print("tool **really executed it** on a fork of the environment. *referential* is")
    print("the subset where the substituted value names another record of the same")
    print("kind in the environment (same structural slot), i.e. the admitted call acts")
    print("on a different object rather than carrying different payload text.\n")

    print("## 3. What the monitor does distinguish\n")
    print("Pairs where the original was admitted and the substitution refused: the")
    print("monitor *has* a distinguishing feature, and this is its name.\n")
    print("| run | tool · arg | n | denial category | observation components that differ |")
    print("|---|---|---|---|---|")
    for d in runs:
        c: collections.Counter = collections.Counter()
        for p in d["pairs"]:
            if p["bucket"] == "orig_allowed_sub_denied":
                c[(p["tool"], p["arg"], p["sub_verdict"]["category"],
                   tuple(p["pi_difference"]))] += 1
        for (tool, arg, cat, diff), n in c.most_common():
            print(f"| {d['summary']['suite']} · {d['summary']['config']} | `{tool}.{arg}` "
                  f"| {n} | {cat} | {', '.join(diff) or '—'} |")
    print()

    print("## 4. Referential forced admissions, by argument slot\n")
    print("The census rows. `role` is this experiment's reporting label, not part of")
    print("the monitor's observation: `observed_driving` = the argument the taint")
    print("decision keys on, `selector` = an argument that names the record acted on,")
    print("`payload` = anything else.\n")
    print("| run | tool · arg | role | n | slot | example |")
    print("|---|---|---|---|---|---|")
    for d in runs:
        c: collections.Counter = collections.Counter()
        ex: dict[Any, dict] = {}
        for p in d["pairs"]:
            if (p["bucket"] == "orig_allowed_sub_allowed" and p["pi_equal"]
                    and p["dispatch_ok"] and p["same_slot"]):
                key = (p["tool"], p["arg"], p["arg_role"],
                       (p["original_slots"] or ["—"])[0])
                c[key] += 1
                ex.setdefault(key, p)
        for (tool, arg, role, slot), n in c.most_common():
            p = ex[(tool, arg, role, slot)]
            print(f"| {d['summary']['suite']} · {d['summary']['config']} | `{tool}.{arg}` "
                  f"| {role} | {n} | `{_fmt(slot, 44)}` | {p['task']}: "
                  f"`{_fmt(p['original_value'], 26)}` → `{_fmt(p['candidate_value'], 26)}` |")
    print()

    print("## 5. Every referential forced admission\n")
    print("The full list, so the aggregate above can be checked row by row.\n")
    print("| run | task | step | call | arg | needed value | admitted alternative | monitor's view of both |")
    print("|---|---|---|---|---|---|---|---|")
    for d in runs:
        for p in d["pairs"]:
            if (p["bucket"] == "orig_allowed_sub_allowed" and p["pi_equal"]
                    and p["dispatch_ok"] and p["same_slot"]):
                pi = p["orig_verdict"]
                print(f"| {d['summary']['suite']}·{d['summary']['config'].replace('.yaml','')} "
                      f"| {p['task']} | {p['step']} | `{p['tool']}` | `{p['arg']}` "
                      f"| `{_fmt(p['original_value'], 30)}` | `{_fmt(p['candidate_value'], 30)}` "
                      f"| allowed, {pi['category']} |")
    print()

    if args.enrichment:
        with open(args.enrichment) as fh:
            enr = json.load(fh)
        print("## 6. Step 4 — which additional ground separates a confirmed pair\n")
        print("The cases are the hand-checked ones in `cases.py`; each ground is")
        print("installed on the real governor and both calls are re-judged from the")
        print("same prefix.\n")
        print("| case | ground | needed call | alternative | separates |")
        print("|---|---|---|---|---|")
        for r in enr["pairs"]:
            print(f"| {r['case']} | {r['ground']} "
                  f"| {'allowed' if r['needed_allowed'] else 'REFUSED'} "
                  f"| {'allowed' if r['alternative_allowed'] else 'refused'} "
                  f"| {'yes' if r['separates'] else 'no'} |")
        print("\n### What the deployment-wide grounds cost\n")
        print("Of the effectful calls the reference plans make, how many the monitor")
        print("still admits. No utility *gain* is claimed for any ground.\n")
        print("| suite · config | ground | needed effectful calls | still admitted |")
        print("|---|---|---|---|")
        for c in enr["costs"]:
            print(f"| {c['suite']} · {c['config']} | {c['ground']} "
                  f"| {c['needed_effectful_calls']} | {c['admitted']} |")
        print()

    if args.neighbor:
        print("## 7. Step 5 — the same pairs through a real neighbouring engine (OPA)\n")
        print("`call_only.rego` is the engine with the call and the operator's static")
        print("facts; `with_labels.rego` is the same engine handed axor's per-value")
        print("origin labels and the floor boolean. Configurations are in `neighbor/`")
        print("and the exact input JSON for every row is written beside the verdicts.\n")
        print("| ground | case | axor needed/alt | OPA call-only | OPA with labels | separates |")
        print("|---|---|---|---|---|---|")
        agree_wl = agree_co = total = 0
        for path in sorted(glob.glob(os.path.join(args.neighbor, "verdicts-*.json"))):
            with open(path) as fh:
                rows = json.load(fh)
            for r in rows:
                def v(side: str, key: str) -> str:
                    return "allow" if r[side][key]["allowed"] else "deny"
                sep = [
                    name for name, key in (("axor", "axor"), ("call-only", "opa_call_only"),
                                           ("with-labels", "opa_with_labels"))
                    if r["needed"][key]["allowed"] and not r["alternative"][key]["allowed"]
                ]
                print(f"| {r['ground']} | {r['case']} | {v('needed','axor')}/{v('alternative','axor')} "
                      f"| {v('needed','opa_call_only')}/{v('alternative','opa_call_only')} "
                      f"| {v('needed','opa_with_labels')}/{v('alternative','opa_with_labels')} "
                      f"| {', '.join(sep) or 'none'} |")
                for side in ("needed", "alternative"):
                    total += 1
                    agree_wl += int(r[side]["axor"]["allowed"] == r[side]["opa_with_labels"]["allowed"])
                    agree_co += int(r[side]["axor"]["allowed"] == r[side]["opa_call_only"]["allowed"])
        print(f"\n{total} verdicts compared: the engine handed axor's observations agrees")
        print(f"with axor on {agree_wl}/{total}; the engine without them agrees on")
        print(f"{agree_co}/{total}, and never separates a pair axor cannot.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
